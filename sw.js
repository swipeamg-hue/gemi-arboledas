async function notifyClients(payload) {
  const list = await self.clients.matchAll({ includeUncontrolled: true });
  for (const c of list) c.postMessage(payload);
}

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const total = PRECACHE_ASSETS.length;
    let done = 0;
    const BATCH = 10;
    for (let i = 0; i < total; i += BATCH) {
      const slice = PRECACHE_ASSETS.slice(i, i + BATCH);
      await Promise.all(slice.map(async (assetUrl) => {
        try {
          const res = await fetch(new Request(assetUrl, { cache: 'reload' }));
          if (res && res.ok) await cache.put(assetUrl, res);
        } catch (e) {}
        done++;
      }));
      await notifyClients({ type: 'SW_PROGRESS', done, total });
    }
    await notifyClients({ type: 'SW_READY', total });
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(k => k !== CACHE_NAME).map(k => caches.delete(k)));
    await self.clients.claim();
    await notifyClients({ type: 'SW_READY', total: PRECACHE_ASSETS.length });
  })());
});

async function buildRangeResponse(request, cachedRes) {
  const rangeHeader = request.headers.get('range');
  if (!rangeHeader) return cachedRes;
  const buf = await cachedRes.arrayBuffer();
  const match = /bytes=(\d+)-(\d*)/.exec(rangeHeader);
  if (!match) return cachedRes;
  const start = Number(match[1]);
  const end = match[2] ? Math.min(Number(match[2]), buf.byteLength - 1) : buf.byteLength - 1;
  const chunk = buf.slice(start, end + 1);
  return new Response(chunk, {
    status: 206,
    statusText: 'Partial Content',
    headers: {
      'Content-Type': cachedRes.headers.get('Content-Type') || 'audio/mpeg',
      'Content-Range': `bytes ${start}-${end}/${buf.byteLength}`,
      'Content-Length': String(chunk.byteLength),
      'Accept-Ranges': 'bytes'
    }
  });
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      try {
        const netNav = await fetch(req);
        if (netNav && netNav.ok) cache.put('./index.html', netNav.clone());
        return netNav;
      } catch (e) {
        return (await cache.match('./index.html')) || (await cache.match('./')) || Response.error();
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = (await cache.match(req, { ignoreSearch: true })) || (await cache.match(url.pathname));
    if (cached) return buildRangeResponse(req, cached);

    try {
      const netRes = await fetch(req);
      if (netRes && netRes.ok && !req.headers.get('range')) {
        cache.put(req, netRes.clone());
      }
      return netRes;
    } catch (e) {
      return Response.error();
    }
  })());
});
